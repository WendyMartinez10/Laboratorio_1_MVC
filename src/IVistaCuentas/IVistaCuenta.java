    private void btnDepositarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDepositarActionPerformed
     try {
         String cuenta = txtCuentaOrigen.getText();
         String montotexto = txtMonto.getText();
         
         if (cuenta.isBlank() || montotexto.isBlank()) {
             mostrarError("Debe ingresar  la cuenta y el monto");
             return;
         }
         double monto = Double.parseDouble(montotexto);
         if(monto <= 0) {
         mostrarError("El monto debe ser mayor a cero");
         return;
     }
         controlador.depositar(cuenta,monto);
         mostrarMensaje("Deposito realizado correctamente");
     } catch (NumberFormatException ex) {
         mostrarError("El monto debe ser un numero valido");
     } catch(Exception ex) {
         mostrarError(ex.getMessage());
     }
    }//GEN-LAST:event_btnDepositarActionPerformed

