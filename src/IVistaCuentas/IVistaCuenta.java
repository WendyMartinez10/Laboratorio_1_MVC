    private void bntCrearCuentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bntCrearCuentaActionPerformed
        try {
        String numero = txtNumeroCuenta.getText();
        String titular = txtTitular.getText();
        String saldoTexto = txtSaldoInicial.getText();
        String moneda = cmbMoneda.getSelectedItem().toString();

        if (numero.isBlank() || titular.isBlank() || saldoTexto.isBlank()) {
            mostrarError("Todos los campos son obligatorios");
            return;
        }

        double saldo = Double.parseDouble(saldoTexto);
        if (saldo < 0) {
            mostrarError("El saldo inicial no puede ser negativo");
            return;
        }

        CuentaBancaria cuenta = moneda.equals("Colones")
            ? new CuentaColonea(numero, titular, saldo)
            : new CuentaDolares(numero, titular, saldo);

        controlador.CrearCuenta(cuenta);
    } catch (NumberFormatException ex) {
        mostrarError("El saldo debe ser un número válido");
    } catch (Exception ex) {
        mostrarError(ex.getMessage());
    }
    }//GEN-LAST:event_bntCrearCuentaActionPerformed

